#[test]
fn endpoints_can_choose_different_frontends_and_preserve_native_metadata() {
    let docs = documents(render(
        r#"
ingress:
  api:
    enabled: true
    hosts: [s3.example.com, "*.s3.example.com"]
    labels: {team: storage}
    annotations: {example.com/policy: streaming}
httpRoute:
  console:
    enabled: true
    parentRefs: [{name: shared, sectionName: https, port: 443}]
    hostnames: [console.example.com]
"#,
        &[],
    ));
    assert_eq!(docs.len(), 3);
    let ingress = docs.iter().find(|d| d["kind"] == "Ingress").unwrap();
    assert_eq!(ingress["metadata"]["labels"]["team"], "storage");
    assert_eq!(
        ingress["metadata"]["annotations"]["example.com/policy"],
        "streaming"
    );
    assert_eq!(ingress["spec"]["rules"][1]["host"], "*.s3.example.com");
    let route = docs.iter().find(|d| d["kind"] == "HTTPRoute").unwrap();
    assert_eq!(route["metadata"]["name"], "rustfs-console");
    assert_eq!(route["spec"]["parentRefs"][0]["port"].as_i64(), Some(443));
    assert_resource_boundary(&docs);
}

#[test]
fn invalid_networking_values_fail_offline_instead_of_silently_exposing() {
    for values in [
        "ingress: {api: {enabled: true}}",
        "httpRoute: {api: {enabled: true}}",
        "ingress: {api: {enabled: true, hosts: [s3.example.com]}}\nhttpRoute: {api: {enabled: true}}",
        "tenant: {metadata: {name: 9invalid}}",
        "tenant: {spec: {pools: []}}",
        "httpRoute: {api: {enabled: true, parentRefs: [{name: shared, kind: Service}], hostnames: [s3.example.com]}}",
        "httpRoute: {api: {backendTLS: {hostname: s3.example.com}}}",
        "ingress: {api: {enable: true}}",
    ] {
        let output = render(values, &[]);
        assert!(
            !output.status.success(),
            "invalid values unexpectedly rendered: {values}"
        );
        assert!(!output.stderr.is_empty());
    }
}

#[test]
fn plain_yaml_examples_use_the_same_service_contract() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let base = std::fs::read_to_string(root.join("examples/networking/base/tenant.yaml")).unwrap();
    let tenant: Tenant = serde_yaml_ng::from_str(&base).unwrap();
    tenant.validate_pools().unwrap();
    for file in [
        "ingress/ingress.yaml",
        "gateway/httproute.yaml",
        "gateway/backend-tls.yaml",
    ] {
        let yaml = std::fs::read_to_string(root.join("examples/networking").join(file)).unwrap();
        for doc in serde_yaml_ng::Deserializer::from_str(&yaml) {
            let value = Value::deserialize(doc).unwrap();
            let name = value["metadata"]["name"].as_str().unwrap();
            let service = if name == "rustfs-api" {
                tenant.new_io_service()
            } else {
                tenant.new_console_service()
            };
            let target = match value["kind"].as_str().unwrap() {
                "Ingress" => {
                    &value["spec"]["rules"][0]["http"]["paths"][0]["backend"]["service"]["name"]
                }
                "HTTPRoute" => &value["spec"]["rules"][0]["backendRefs"][0]["name"],
                "BackendTLSPolicy" => &value["spec"]["targetRefs"][0]["name"],
                other => panic!("unexpected example resource: {other}"),
            };
            assert_eq!(target.as_str(), service.metadata.name.as_deref());
        }
    }
}
